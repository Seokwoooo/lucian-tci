/** Subscales whose item content is political, religious, or gender-stereotyped are never headlined. */
export const NO_HEADLINE = new Set(['ST4', 'ST5']);

export function band(mean: number): 'high' | 'middle' | 'low' {
  return mean <= 2.5 ? 'low' : mean >= 3.5 ? 'high' : 'middle';
}

export function subscaleSentence(code: string, mean: number): string {
  const line = subscaleLines[code];
  const level = band(mean);
  if (level === 'middle') return `상황에 따라 달라요. “${line.high}”와 “${line.low}”가 섞여 있어요.`;
  return line[level];
}
